const FOOD_IMAGE_LEVELS = {
  "Cereal and bread": 1,
  "Eggs and Dairy": 1,
  "Fast food": 4,
  "Fish and meat": 3,
  Fruits: 2,
  Sweets: 4,
  Vegetables: 2,
};

const foodImagesInDatabase = new Set(
  Object.values(window.FOOD_DATABASE)
    .flat()
    .map((food) => food.image),
);

Object.entries(FOOD_IMAGE_FILES_BY_FOLDER).forEach(([folder, fileList]) => {
  const levelId = FOOD_IMAGE_LEVELS[folder];
  fileList.split("\n").forEach((fileName) => {
    const image = `${folder}/${fileName}`;
    if (foodImagesInDatabase.has(image)) return;

    const baseName = fileName
      .replace(/(?:\s+\d+)?\.png$/i, "")
      .trim()
      .toLowerCase();
    let type = "produce";
    let flavor = "savory";
    if (folder === "Cereal and bread") {
      type = ["cookies", "pie"].includes(baseName) ? "junk" : "carb";
      flavor =
        baseName === "cookies"
          ? "sweet"
          : baseName === "pie"
            ? "savory"
            : "neutral";
    } else if (folder === "Eggs and Dairy") {
      type = baseName === "butter" ? "junk" : "protein";
      flavor =
        baseName === "yogurt"
          ? "sweet"
          : ["egg", "cheese"].includes(baseName)
            ? "savory"
            : "neutral";
    } else if (folder === "Fast food" || folder === "Sweets") {
      type = "junk";
      flavor =
        folder === "Sweets" ||
        ["cola", "energy drink"].includes(baseName)
          ? "sweet"
          : "savory";
    } else if (folder === "Fish and meat") {
      type = "protein";
      flavor = "savory";
    } else if (folder === "Fruits") {
      type = "produce";
      flavor = baseName === "lemon" ? "neutral" : "sweet";
    } else if (folder === "Vegetables") {
      type = baseName === "potato" ? "carb" : "produce";
      flavor = baseName === "potato" ? "neutral" : "savory";
    }

    const name = FOOD_IMAGE_NAMES[baseName] || baseName;
    const isJunk = type === "junk";
    const points =
      ["cola", "energy drink", "sugar"].includes(baseName)
        ? -15
        : isJunk
          ? -10
          : 15;
    const item = {
      id: `asset-${folder}-${baseName}-${fileName.match(/\d+/)?.[0] || "1"}`
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-"),
      name,
      flavor,
      type,
      image,
      points,
      healthy: !isJunk,
      tag:
        type === "carb"
          ? "Süsivesikud"
          : type === "protein"
            ? "Valgud"
            : type === "produce"
              ? "Puu- või köögivili"
              : "Maiustus või rämpstoit",
    };

    window.FOOD_DATABASE[levelId].push(item);
    foodImagesInDatabase.add(image);
  });
});

function inferFoodMealType(food) {
  const image = String(food.image || "").toLowerCase();
  const fileName = image.split("/").pop() || "";
  const baseName = fileName.replace(/(?:\s+\d+)?\.png$/i, "");
  const folder = image.split("/").slice(0, -1).join("/");
  const name = String(food.name || "").toLowerCase();

  if (
    ["cereal", "porridge"].includes(baseName) ||
    /hommikusöögihelbed|kaerahelbepuder/.test(name)
  ) {
    return ["breakfast"];
  }
  if (folder === "fruits" || ["cucumber", "tomato"].includes(baseName)) {
    return ["any"];
  }
  if (
    ["riis", "tatar", "spaghetty", "potato"].includes(baseName) ||
    folder === "fish and meat" ||
    folder === "vegetables"
  ) {
    return ["main_meal"];
  }
  if (
    folder === "cereal and bread" &&
    ["cookies", "pie"].includes(baseName)
  ) {
    return ["any"];
  }
  if (folder === "cereal and bread" || folder === "eggs and dairy") {
    return ["breakfast", "main_meal"];
  }
  return ["any"];
}

